export type SoundInfo = { name: string; label: string; ms: number; pet: boolean };

/** The earcons play whether or not pet sounds are on. */
const EARCONS = new Set(["wake", "error", "alarm", "volume"]);

const LABELS: Record<string, string> = { uh_oh: "Uh-oh", tada: "Ta-da!", pfft: "Pfft", eep: "Eep!", boo: "Boo!" };

export const SOUND_LIST: SoundInfo[] = Object.entries(SOUNDS).map(([name, tones]) => ({
  name,
  label: LABELS[name] ?? name[0].toUpperCase() + name.slice(1).replace(/_/g, " "),
  ms: tones.reduce((sum, t) => sum + t[2], 0),
  pet: !EARCONS.has(name),
}));

/** synth_render() in main/sounds.c: the whole sound, as samples -1..1. */
export function render(name: string): Float32Array {
  const tones = SOUNDS[name] ?? [];
  const total = tones.reduce((sum, t) => sum + (t[2] * RATE) / 1000, 0);
  const out = new Float32Array(total);
  let rng = 0x9e3779b9;
  let lp1 = 0;
  let lp2 = 0;
  let phase = 0;
  let at = 0;
  const noise = () => {
    rng ^= rng << 13;
    rng ^= rng >>> 17;
    rng ^= rng << 5;
    return (rng | 0) / 2147483648;
  };
  const filtered = (corner: number) => {
    const a = 1 - Math.exp((-PI2 * corner) / RATE);
    lp1 += a * (noise() - lp1);
    lp2 += a * (lp1 - lp2);
    return (lp2 * 0.9) / Math.sqrt(a / (2 - a));
  };
  const buzz = (p: number) => (Math.sin(p) + 0.5 * Math.sin(2 * p) + 0.25 * Math.sin(3 * p)) / 1.4;
  for (const [f0, f1, ms, wave, vol, vib, rate, env] of tones) {
    const n = (ms * RATE) / 1000;
    let freq = f0;
    const step = f0 > 0 && f1 > 0 ? Math.pow(f1 / f0, 1 / n) : 1;
    let decay = 1;
    const decayStep = Math.exp(-PLUCK_DECAY / n);
    let fade = (FADE_MS * RATE) / 1000;
    if (fade > Math.floor(n / 4)) fade = Math.max(1, Math.floor(n / 4));
    for (let k = 0; k < n; k++, at++) {
      if (f0 === 0) continue;
      let g = (AMPLITUDE * vol) / 100;
      if (k < fade) g *= k / fade;
      else if (n - k < fade) g *= (n - k) / fade;
      const secs = k / RATE;
      if (env & SWELL) g *= Math.sin((Math.PI * k) / n);
      if (env & PLUCK) {
        g *= decay;
        decay *= decayStep;
      }
      if (env & TREM) g *= 0.5 - 0.5 * Math.cos(PI2 * rate * secs);
      let f = freq;
      freq *= step;
      if (vib > 0) f *= 1 + (vib / 100) * Math.sin(PI2 * rate * secs);
      let v: number;
      if (wave === Wave.Noise) v = filtered(f);
      else {
        phase += (PI2 * f) / RATE;
        if (phase >= PI2) phase -= PI2;
        const p = phase;
        v =
          wave === Wave.Tri
            ? 4 * Math.abs(p / PI2 - 0.5) - 1
            : wave === Wave.Buzz
              ? buzz(p)
              : wave === Wave.Breath
                ? 0.7 * buzz(p) + 0.5 * filtered(4 * f)
                : Math.sin(p);
      }
      out[at] = Math.max(-1, Math.min(1, (g * v) / 32768));
    }
  }
  return out;
}

let audio: AudioContext | null = null;
let playing: AudioBufferSourceNode | null = null;

/** Play `name` on this computer's speakers, louder than on the board. */
export function playHere(name: string) {
  audio ??= new AudioContext();
  const samples = render(name);
  const buffer = audio.createBuffer(1, samples.length, RATE);
  buffer.copyToChannel(samples.map((s) => s * 2.5), 0);
  playing?.stop();
  playing = audio.createBufferSource();
  playing.buffer = buffer;
  playing.connect(audio.destination);
  playing.start();
}
